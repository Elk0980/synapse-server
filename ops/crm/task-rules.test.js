test('observe: nothing is rejected, every would-be rejection is counted and shown in the digest',t=>{
 const {rules,row,card,before,db}=fixture(t,{mode:'observe'});
 rules.seen({rules_revision:REV,rules_version:'1.7'});
 rules.beforeCreate({title:'Экран',description:''},{});
 rules.beforeUpdate(row(),{before,after:card('code','https://github.com/Elk0980/synapse-server/pull/1')},{});
 rules.beforeUpdate(row(),{before,after:card('verified','глазами')},{});
 rules.beforeUpdate(row(),{before,after:card(),status:'done'},{});
 const s=rules.summary(0);
 assert.equal(s.rejected.length,0);assert.equal(s.would_reject.length,5);
 assert.deepEqual(s.non_compliant.map(a=>a.task_id),[1]);assert.equal(s.compliant.length,0);
 const text=rules.lines(s).join('\n');
 assert.match(text,/По правилам: 0\. Не по правилам: 1\./);assert.match(text,/Отклонено бы \(наблюдение, за сутки\): 5/);
 assert.match(text,/№1 · нет якоря/);
 const digest=createTaskWatchdog(db,{now:()=>Date.now(),mode:'observe'}).digest();
 assert.match(digest.text,/Отклонено бы/);assert.equal(digest.rules.mode,'observe');
});
